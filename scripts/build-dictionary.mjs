#!/usr/bin/env node
/**
 * Builds the preset dictionary the inline carrier compresses against.
 *
 * DEFLATE finds repeats inside the data it is given. A small application has
 * few repeats of its own, but it has a great many in common with every other
 * small application built to the same recipe: the kit's element names, the
 * CSS a model reaches for, `CREATE TABLE IF NOT EXISTS`. A preset dictionary
 * is that shared text, handed to both sides in advance, so the compressor can
 * refer to it as though it had already been sent.
 *
 * The corpus is the things a container is most likely to contain: the kit
 * source (every app references it), the recipe (every app was written to it),
 * the shell template, and the example applications' HTML, CSS and SQL. Capped
 * at 32 kB, which is DEFLATE's window and therefore the most that can be
 * referred to.
 *
 * Written to `src/dictionary.ts` as a constant, and identified by the first
 * four bytes of its digest. An opener holding a different dictionary refuses a
 * link that names one it does not have, rather than inflating garbage — the id
 * is what makes that refusal possible, and why the dictionary is versioned by
 * content rather than by hand.
 *
 * Also written as raw bytes to `conformance/inline-dictionary.bin`, for a
 * reader in another language that has to inflate the same links.
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const { KIT_SOURCE } = await import(resolve(root, "dist/kit.js").replace(/\\/g, "/").replace(/^([A-Za-z]):/, "file:///$1:"));
const { RECIPE } = await import(resolve(root, "dist/recipe.js").replace(/\\/g, "/").replace(/^([A-Za-z]):/, "file:///$1:"));

const LIMIT = 32 * 1024;

const pieces = [
  // Most valuable last: DEFLATE distances are cheaper to nearer text, and the
  // end of the dictionary is nearest to the start of the data.
  RECIPE,
  readFileSync(resolve(root, "dist/template.html"), "utf8"),
  ...["chore-chart", "meal-plan", "packing-list"].flatMap((app) =>
    ["schema.sql", "app.css", "index.html"].map((file) => {
      try {
        return readFileSync(resolve(root, "examples", app, file), "utf8");
      } catch {
        return "";
      }
    }),
  ),
  KIT_SOURCE,
];

let text = pieces.join("\n");
const encoder = new TextEncoder();
let bytes = encoder.encode(text);
if (bytes.length > LIMIT) {
  // Trim from the front: the front is the least valuable end.
  bytes = bytes.subarray(bytes.length - LIMIT);
  // Do not start mid-character.
  let start = 0;
  while (start < 4 && (bytes[start] & 0xc0) === 0x80) start++;
  bytes = bytes.subarray(start);
}

const digest = createHash("sha256").update(bytes).digest();
const id = digest.subarray(0, 4);

const out = `/**
 * The inline carrier's preset dictionary. GENERATED by scripts/build-dictionary.mjs.
 *
 * ${bytes.length} bytes of the text a small application is most likely to share
 * with every other: the kit, the recipe, the shell template and the example
 * applications. Identified by the first four bytes of its SHA-256, so a link
 * names the dictionary it was compressed against and an opener that does not
 * hold that one refuses rather than inflating garbage.
 *
 * Do not edit. Change the corpus in the script and run it.
 */
import { fromBase64 } from "./core.js";

export const DICTIONARY_ID = Uint8Array.from([${[...id].join(", ")}]);
export const DICTIONARY = fromBase64(
  "${Buffer.from(bytes).toString("base64")}",
);
`;

writeFileSync(resolve(root, "src/dictionary.ts"), out, "utf8");
mkdirSync(resolve(root, "conformance"), { recursive: true });
writeFileSync(resolve(root, "conformance/inline-dictionary.bin"), bytes);

console.log(`dictionary: ${bytes.length} bytes, id ${Buffer.from(id).toString("hex")}`);
