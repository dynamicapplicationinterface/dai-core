#!/usr/bin/env node
/**
 * Builds the UTS #39 confusable table the hosts and the Python reader share.
 *
 * Two names are "the same name" to a person's eye when their confusable
 * skeletons match (UTS #39 §4). The skeleton needs the table, and three
 * implementations computing skeletons from three copies of the table would
 * disagree the first time one copy was updated. So there is one table, content
 * hashed, and every host loads the same bytes:
 *
 *   conformance/confusables.json               — the canonical copy
 *   conformance/confusables.<hash8>.json       — the same bytes, hashed name
 *   apps/runner/public/confusables.<hash8>.json — staged for the opener
 *   src/confusables-id.ts                      — the hash, so code knows the name
 *
 * Source: https://www.unicode.org/Public/security/latest/confusables.txt,
 * downloaded when `--fetch` is given or the cached copy is absent. The table is
 * not normative — the conformance vectors are — so a host MAY use newer data;
 * what matters is that the hosts we ship agree with each other.
 *
 * Format: { "unicode": "17.0.0", "map": { "<source char>": "<target string>" } }
 * Only the prototype (MA) mappings, which is all UTS #39 §4 uses.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const cache = join(root, "conformance", "confusables.txt");
const url = "https://www.unicode.org/Public/security/latest/confusables.txt";

/*
 * `--check`: rebuild from the cached table and compare with what is committed,
 * writing nothing and never downloading. Four copies of one table are
 * committed; a table rebuilt without restaging them all is hosts that disagree
 * about which names look alike.
 */
const checking = process.argv.includes("--check");
if (checking && !existsSync(cache)) {
  console.error("confusables: conformance/confusables.txt is missing, and a check never downloads.");
  process.exit(1);
}

if (!checking && (process.argv.includes("--fetch") || !existsSync(cache))) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} → HTTP ${response.status}`);
  writeFileSync(cache, await response.text(), "utf8");
}

const text = readFileSync(cache, "utf8");
const version = /# Version: ([\d.]+)/.exec(text)?.[1] ?? "unknown";

const map = {};
for (const line of text.split("\n")) {
  const body = line.split("#")[0].trim();
  if (!body) continue;
  const [source, target, type] = body.split(";").map((part) => part.trim());
  if (type !== "MA") continue;
  const from = String.fromCodePoint(...source.split(/\s+/).map((h) => parseInt(h, 16)));
  const to = String.fromCodePoint(...target.split(/\s+/).map((h) => parseInt(h, 16)));
  map[from] = to;
}

const json = JSON.stringify({ unicode: version, map });
const hash = createHash("sha256").update(json).digest("hex").slice(0, 8);

const outputs = new Map([
  [join(root, "conformance", "confusables.json"), json],
  [join(root, "conformance", `confusables.${hash}.json`), json],
  [join(root, "apps", "runner", "public", `confusables.${hash}.json`), json],
  [
    join(root, "src", "confusables-id.ts"),
    `/** GENERATED by scripts/build-confusables.mjs. The UTS #39 table every host loads, by content hash. */\n` +
      `export const CONFUSABLES_ID = "${hash}";\n` +
      `export const CONFUSABLES_UNICODE = "${version}";\n` +
      `export const CONFUSABLES_FILE = \`confusables.\${CONFUSABLES_ID}.json\`;\n`,
  ],
]);

if (checking) {
  const rel = (path) => path.slice(root.length + 1).replace(/\\/g, "/");
  const stale = [...outputs]
    .filter(([path, text]) => !existsSync(path) || readFileSync(path, "utf8").replace(/\r\n/g, "\n") !== text)
    .map(([path]) => rel(path));
  // A hashed copy of a table that is no longer the table: served by nothing,
  // and the next person to look will not know which one is real.
  const orphans = ["conformance", join("apps", "runner", "public")].flatMap((dir) =>
    readdirSync(join(root, dir))
      .filter((name) => /^confusables\.[0-9a-f]{8}\.json$/.test(name) && name !== `confusables.${hash}.json`)
      .map((name) => `${dir.replace(/\\/g, "/")}/${name}`),
  );
  if (stale.length > 0 || orphans.length > 0) {
    console.error(
      "The confusable table is out of date — run node scripts/build-confusables.mjs\n" +
        stale.map((path) => `  stale: ${path}\n`).join("") +
        orphans.map((path) => `  orphan: ${path}\n`).join(""),
    );
    process.exit(1);
  }
  console.log(`confusables: current (Unicode ${version}, id ${hash})`);
  process.exit(0);
}

mkdirSync(join(root, "apps", "runner", "public"), { recursive: true });
for (const [path, text] of outputs) writeFileSync(path, text, "utf8");

console.log(`confusables: Unicode ${version}, ${Object.keys(map).length} mappings, ${(json.length / 1024).toFixed(0)} kB, id ${hash}`);
