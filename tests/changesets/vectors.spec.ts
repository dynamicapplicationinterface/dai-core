import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { expect, test } from "@playwright/test";
import { SCENARIOS, base, verdictsOf } from "./scenarios.js";
import { Copy, openBytes } from "./copy.js";

/**
 * The changeset vectors (R-Q): R-O's data interface gets readers on the same
 * footing as the authorship layer, starting with these.
 *
 * Each vector is one merge scenario's two copies, as stored after each wrote
 * concurrently, with the verdicts their headers get and what applying the
 * admitted log must give in each direction. The bytes are signed with fresh
 * keys, so they are written once and committed, never regenerated by a check:
 *
 *   DAI_WRITE_CHANGESET_VECTORS=1 npx playwright test tests/changesets/vectors.spec.ts --project=node
 *
 * The check is in the consumers (the runtime, here, and the Python reader),
 * against the committed files, so the generator cannot pass itself.
 */

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const ROOT = join(repo, "conformance", "changesets");
const PYTHON = process.platform === "win32" ? "python" : "python3";

/** The vectors, each from one merge scenario (`scenarios.ts`). */
const VECTORS: Record<string, string> = {
  "different-rows": "S1 inserts",
  "different-columns": "S2 columns",
  "same-column": "S3 same column",
  "delete-update": "S4 delete/update",
  "trigger-suppressed": "S8 app trigger",
  "key-moved": "K12 key moved",
  "returning": "D07 returning",
  "resolution": "RW-12 resolution",
  "respelled-key": "1e-H3 respelled key",
};

interface Applied {
  tables: unknown;
  flags: [string, string, string][];
  held: [string, string][];
}

const applied = (c: Copy): Applied => ({
  tables: c.dump(),
  flags: c.flags().map((f: { tbl: string; pk: string; kind: string }) => [f.tbl, f.pk, f.kind] as [string, string, string]).sort(),
  held: c.held().map((h: { tbl: string; pk: string }) => [h.tbl, h.pk] as [string, string]).sort(),
});

/** The author a stored copy names as its own, opened as that author, as its host would. */
async function reopen(bytes: Uint8Array): Promise<Copy> {
  const { db } = await openBytes(bytes);
  const author = db.selectValue("SELECT id FROM _dai_replica LIMIT 1") as Uint8Array;
  db.close();
  return Copy.open({ author, keys: undefined as unknown as CryptoKeyPair, shown: "" }, bytes);
}

/** One direction under the runtime: `mine` merges `theirs` and projects. */
async function runtimeApplies(mine: Uint8Array, theirs: Uint8Array): Promise<Applied & { refused: string[] }> {
  const c = await reopen(mine);
  const { report } = await c.mergeFrom(theirs);
  const out = { ...applied(c), refused: (report.refusedBatches ?? []).map((r: { reason: string }) => r.reason) };
  c.close();
  return out;
}

test("write the changeset vectors (only when asked)", async () => {
  test.skip(process.env["DAI_WRITE_CHANGESET_VECTORS"] !== "1", "the vectors are committed; set DAI_WRITE_CHANGESET_VECTORS=1 to write them again");
  test.setTimeout(180_000);
  for (const [name, scenario] of Object.entries(VECTORS)) {
    // Written once: a vector already committed keeps its bytes.
    if (existsSync(join(ROOT, name))) continue;
    const s = SCENARIOS[scenario]!;
    const { a, b } = await base({ trigger: s.trigger, extra: s.extra });
    await s.write(a, b);
    const aBytes = await a.bytes();
    const bBytes = await b.bytes();
    a.close();
    b.close();
    const dir = join(ROOT, name);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, "a.db"), aBytes);
    writeFileSync(join(dir, "b.db"), bBytes);
    writeFileSync(join(dir, "verdicts.json"), JSON.stringify({ a: await verdictsOf(aBytes), b: await verdictsOf(bBytes) }, null, 2) + "\n");
    const ab = await runtimeApplies(aBytes, bBytes);
    const ba = await runtimeApplies(bBytes, aBytes);
    expect([...ab.refused, ...ba.refused], name).toEqual([]);
    const strip = ({ tables, flags, held }: Applied): Applied => ({ tables, flags, held });
    writeFileSync(join(dir, "expected.json"), JSON.stringify({ scenario, ab: strip(ab), ba: strip(ba) }, null, 2) + "\n");
  }
});

test("the vectors are committed, one per scenario", () => {
  expect(existsSync(ROOT), "conformance/changesets exists").toBe(true);
  const dirs = readdirSync(ROOT, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
  expect(dirs).toEqual(Object.keys(VECTORS).sort());
  for (const name of dirs) {
    for (const file of ["a.db", "b.db", "verdicts.json", "expected.json"]) expect(existsSync(join(ROOT, name, file)), `${name}/${file}`).toBe(true);
    expect(JSON.parse(readFileSync(join(ROOT, name, "expected.json"), "utf8")).scenario).toBe(VECTORS[name]);
  }
});

test("the runtime applies every committed vector as expected, both directions", async () => {
  test.setTimeout(120_000);
  for (const name of Object.keys(VECTORS)) {
    const dir = join(ROOT, name);
    const expected = JSON.parse(readFileSync(join(dir, "expected.json"), "utf8"));
    const a = new Uint8Array(readFileSync(join(dir, "a.db")));
    const b = new Uint8Array(readFileSync(join(dir, "b.db")));
    for (const [direction, mine, theirs] of [["ab", a, b], ["ba", b, a]] as const) {
      const got = await runtimeApplies(mine, theirs);
      expect(got.refused, `${name} ${direction}`).toEqual([]);
      expect({ tables: got.tables, flags: got.flags, held: got.held }, `${name} ${direction}`).toEqual(expected[direction]);
    }
  }
});

test("the Python reader passes every committed vector", () => {
  const run = spawnSync(PYTHON, ["-I", join(repo, "conformance", "reference", "dai_changes.py"), "--vectors", ROOT], { encoding: "utf8" });
  expect(run.stderr).toBe("");
  expect(run.stdout.trim().split(/\r?\n/).pop()).toBe(`${Object.keys(VECTORS).length * 2}/${Object.keys(VECTORS).length * 2} passed`);
  expect(run.status).toBe(0);
});
